#!/usr/bin/env python3
"""Rasterize printable ASCII into the loader's 8x16 1-bit font, as a C header -- without a Mac (tools/mkfont8x16.swift is the
Mac's way). Uses a font installed on this machine, DejaVu Sans Mono by default (Pillow needed).

  mkfont8x16.py [font.ttf] > mtkloader/font8x16.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

W, H = 8, 16
CANDIDATES = ['/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', '/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf',
              'C:/Windows/Fonts/consolab.ttf', 'C:/Windows/Fonts/consola.ttf']
path = sys.argv[1] if len(sys.argv) > 1 else next(p for p in CANDIDATES if __import__('os').path.exists(p))
font = ImageFont.truetype(path, 13)
print(f'/* Generated by tools/mkfont8x16.py from {path.split("/")[-1]}: ASCII 0x20-0x7e, 8x16, MSB = left. Not kept in git. */')
print('static const unsigned char font8x16[95][16] = {')
for code in range(0x20, 0x7f):
    img = Image.new('L', (W, H), 0)
    ImageDraw.Draw(img).text((0, 0), chr(code), fill=255, font=font)
    rows = []
    for y in range(H):
        b = 0
        for x in range(W):
            if img.getpixel((x, y)) > 100:
                b |= 0x80 >> x
        rows.append(f'0x{b:02x}')
    print(f'\t{{ {", ".join(rows)} }}, /* {chr(code) if code != 0x5c else "backslash"} */')
print('};')
